char OutDisp ()                                                                 // динамическая индикация и "сканирование клавиатуры"
{
static char key=0;                                                              // переменная для хранения номера нажатой кнопки

    PORTD &= ~Bit(0);                                                           // общие аноды разрядов индикатора отключить (погасить) 
    PORTC &= ~Bit(5);
    PORTC &= ~Bit(4);
    PORTC &= ~Bit(3);

  if ((seg[seg_count] & Bit(0)) != 0)   {PORTD &= ~Bit(6);} else {PORTD |= Bit(6);}   // вывод данных на сегменты "соответствующего" индикатора: включение сегмента происходит по нулевому сигналу; например
  if ((seg[seg_count] & Bit(1)) != 0)   {PORTD &= ~Bit(7);} else {PORTD |= Bit(7);}   // seg[0] = 11011000, тогда путем побитного "сравнения" с "11111111" зажечь (напротив 1) или погасить (напротив 0)
  if ((seg[seg_count] & Bit(2)) != 0)   {PORTB &= ~Bit(0);} else {PORTB |= Bit(0);}   // соответствующие сегменты одного индикатора; а также "упорядочивание" выходов портов на сегменты с номером разряда
  if ((seg[seg_count] & Bit(3)) != 0)   {PORTB &= ~Bit(1);} else {PORTB |= Bit(1);}   // 8-бит числа и в соответствии с "a b c d e f g h" : PD6-a(0-й, младший разряд), PD7-b, ..., PB4-g, PD5-h(7-й, старший)
  if ((seg[seg_count] & Bit(4)) != 0)   {PORTB &= ~Bit(2);} else {PORTB |= Bit(2);}
  if ((seg[seg_count] & Bit(5)) != 0)   {PORTB &= ~Bit(3);} else {PORTB |= Bit(3);}
  if ((seg[seg_count] & Bit(6)) != 0)   {PORTB &= ~Bit(4);} else {PORTB |= Bit(4);}
  if ((seg[seg_count] & Bit(7)) != 0)   {PORTD &= ~Bit(5);} else {PORTD |= Bit(5);}

    if (seg_count == 0) {PORTD |= Bit(0);} else {PORTD &= ~Bit(0);}             // включение соответствующего индикатора
    if (seg_count == 1) {PORTC |= Bit(5);} else {PORTC &= ~Bit(5);}
    if (seg_count == 2) {PORTC |= Bit(4);} else {PORTC &= ~Bit(4);}
    if (seg_count == 3) {PORTC |= Bit(3);} else {PORTC &= ~Bit(3);}

  if ((PINC & Bit(2)) != 0) {key |= Bit(seg_count); } else {key &= ~Bit(seg_count);}   // чтение кнопок ("сканирование клавиатуры): если нажата n-кнопка, прописываем в key соответствующий бит по номеру n-кнопки, которая
                                                                                // определяется при включении соответствующего индикатора: (первый (0-вой) - 0001 (1), второй - 0010 (2), 3-й - 0100 (4), 4-й - 1000 (8)
seg_count++;                                                                    // динамический переход на следующий индикатор
if (seg_count > 3) seg_count=0;                                                 // зацикливание функции
return key;                                                                     // вернуть значение key для последующего использования для определения нажатой кнопки
}
