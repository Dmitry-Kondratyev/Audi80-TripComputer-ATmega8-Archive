#define Bit(n) (1 << (n))
/*
  p |= Bit(n);                Для установки бита n в порту p:
  p &= ~Bit(n);               Для сброса бита n в порту p:
  if ((p & Bit(n)) != 0) ...  Для проверки бита n в порту p: (сравнение)
*/
#define EEADR1 10                                                               // коеффициент       (адрес EE, куда сохраняем,
