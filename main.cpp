void SetDataDisp (char mode, unsigned short parameter)                          // представление 16-тиричного числа в виде 10-тичного
{                                                                               // и вывод его посредством строки ("картинки")
char s;
    switch (mode)
    {   case 0:                                                                 // тестовый вывод - "4321"
                break;
        case 1:                                                                 // напряжение
                sprintf (str,"U%3d",parameter);                                 // выводим "U"(напряжение); первые 3 разряды целого 10-тичного числа; 16-тиричную переменную в parameter преобразовываем в 10-тичную и выводим(зажигаем) на индикаторе в виде строки посредством функции getCode
                s=getCode (str[0]); s=s|(1<<7); seg[3]=s;                       // посредством функции getCode зажигаем на 1-ом слева(лв.) индикаторе - "U"; при побитном ИЛИ устанавливаем бит в 7-ом разряде, тем самым зажигая сегмент "h", т.е. точку на 1-ом лв. индикаторе; обновление массива данных для вывода на дисплей(индикаторы), т.е. обновление 1-го лв. индикатора с последующим его зажиганием функцией OutDisp
                s=getCode (str[1]); seg[2]=s;                                   // посредством функции getCode зажигаем на 2-ом лв. индикаторе - 1-ую цифру первых 3-х разрядов(%3d) целого числа, преобразованного из переменной parameter, формула вывода напряжения (в диапазоне ~ 5-18V) выведена в главной ф-ции main (ниже)
                s=getCode (str[2]); s=s|(1<<7); seg[1]=s;
                s=getCode (str[3]); seg[0]=s;
                break;
        case 2:                                                                 // общий расход
                sprintf (str,"F%3d",parameter);
                s=getCode (str[0]); s=s|(1<<7); seg[3]=s;
                s=getCode (str[1]); seg[2]=s;
                s=getCode (str[2]); if (s == 0) {s = 63;} if (parameter < 1000) {s=s|(1<<7);}   seg[1]=s; // также, при нулевом значении выводим на дисплей "0", и если от 0 до 99,9 литров, зажигаем точку на этом индикаторе; при расходе от 100 и больше литров, расход показывается без десятых, в целых литрах
                s=getCode (str[3]); seg[0]=s;                                   // ...если значение "0", на дисплее будут гореть 3 и 4 лв. индикаторы - "0.0"
                break;        
        case 3:                                                                 // часовой расход
                sprintf (str,"H%3d",parameter);
                s=getCode (str[0]); s=s|(1<<7); seg[3]=s;
                s=getCode (str[1]); seg[2]=s;
                s=getCode (str[2]); if (s == 0) {s = 63;} s=s|(1<<7); seg[1]=s;
                s=getCode (str[3]); seg[0]=s;                                   // ..."0.0"
                break;        
        case 4:                                                                 // настройка (поразрядное мигание дисплея; описание "миганий" с 1-го лв. разряда по 4-й)
                sprintf (str,"%04d",parameter); 
                if (g_Hblk == 3)                                                // если надо вывести мигание на 1-й лв. разряд дисплея
                { if (g_Hled == 1) {g_Hled=0; seg[3]=getCode (' '); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);}    // если флаг=1, переводим его в 0 и выполняем все после "if", иначе, если 0, его в 1 и выполняем после "else" : если 1, гасим (пробел) 1-й лв. разряд индикатора, в остальные
                              else {g_Hled=1; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);} // разряды выводим полученные значения из "main", если 0, во все разряды выводим полученные значения из "main", тем самым инициируя режим мигания n-го(1) разряда
                }
                if (g_Hblk == 2) 
                { if (g_Hled == 1) {g_Hled=0; seg[3]=getCode (str[0]); seg[2]=getCode (' '); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);}
                              else {g_Hled=1; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);}
                }
                if (g_Hblk == 1) 
                { if (g_Hled == 1) {g_Hled=0; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (' '); seg[0]=getCode (str[3]);}
                              else {g_Hled=1; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);}
                }
                if (g_Hblk == 0) 
                { if (g_Hled == 1) {g_Hled=0; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (' ');}
                              else {g_Hled=1; seg[3]=getCode (str[0]); seg[2]=getCode (str[1]); seg[1]=getCode (str[2]); seg[0]=getCode (str[3]);}
                }
                break;        
        default: seg[0]=6; seg[1]=91; seg[2]=79; seg[3]=102;                    // по идее быть не должно, но на всякий "пожарный", если что, выведем "4321"
                break;
    }

}
