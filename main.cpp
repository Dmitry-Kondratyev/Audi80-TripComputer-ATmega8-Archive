char getCode (char ch)                                                          // "сопоставление" символам из таблицы ASCII "наших" символов,
{                                                                               // составленных из отдельных сегментов индикаторв при помощи
    switch (ch)                                                                 // представления в десятичном коде, например:
    {   case '0': return  63; // "0"                                            // 63 - 0b00111111, а это "зажечь" сегменты - abcdef, следовательно на индикаторе высветится цифра - 0
        case '1': return   6; // "1"                                            // 0b00000110 - bc
        case '2': return  91; // "2"                                            // 0b01011011 - ab de g
        case '3': return  79; // "3"
        case '4': return 102; // "4"
        case '5': return 109; // "5"
        case '6': return 125; // "6"
        case '7': return   7; // "7"
        case '8': return 127; // "8"
        case '9': return 111; // "9"
        case 'U': return  62; // 
        case 'H': return 118; // 
        case 'F': return 113; // 
        case ' ': return   0; // 
    }
return 1;                                                                       // на всякий, "пожарный" (будет гореть один верхний сегмент "a" на индикаторе)
}
